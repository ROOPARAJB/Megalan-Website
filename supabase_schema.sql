-- 3. Server-Side Validation Trigger Function (Supabase Enforces All Rules)
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.fn_validate_inquiry()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_domain TEXT;
BEGIN
    -- 1. Honeypot Bot Shield (Safe jsonb access)
    IF (to_jsonb(NEW) ? 'bot_honey') AND trim(coalesce(to_jsonb(NEW) ->> 'bot_honey', '')) <> '' THEN
        RAISE EXCEPTION 'Bot submission detected and rejected.';
    END IF;

    -- 2. Normalize and Trim Fields
    NEW.full_name := trim(coalesce(NEW.full_name, ''));
    NEW.email := lower(trim(coalesce(NEW.email, '')));
    NEW.mobile_number := trim(coalesce(NEW.mobile_number, ''));
    NEW.message := trim(coalesce(NEW.message, ''));
    NEW.company_name := nullif(trim(coalesce(NEW.company_name, '')), '');
    NEW.product_variety := nullif(trim(coalesce(NEW.product_variety, '')), '');
    NEW.quantity := nullif(trim(coalesce(NEW.quantity, '')), '');
    NEW.destination := nullif(trim(coalesce(NEW.destination, '')), '');

    -- 3. Length Validations
    IF char_length(NEW.full_name) < 2 OR char_length(NEW.full_name) > 100 THEN
        RAISE EXCEPTION 'Full name must be between 2 and 100 characters.';
    END IF;

    IF char_length(NEW.message) < 5 OR char_length(NEW.message) > 2000 THEN
        RAISE EXCEPTION 'Inquiry message must be between 5 and 2000 characters.';
    END IF;

    -- 4. Email Format Validation
    IF NOT (NEW.email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$') THEN
        RAISE EXCEPTION 'Please provide a valid email address.';
    END IF;

    -- 5. Disposable / Temporary Email Blacklist (Enforced on Database)
    v_domain := split_part(NEW.email, '@', 2);
    IF v_domain IN (
        '10minutemail.com', '10minutemail.net', 'tempmail.com', 'tempmail.net', 'temp-mail.org',
        'mailinator.com', 'guerrillamail.com', 'guerrillamailblock.com', 'guerrillamail.org',
        'guerrillamail.biz', 'guerrillamail.info', 'grr.la', 'sharklasers.com', 'throwawaymail.com',
        'yopmail.com', 'yopmail.net', 'dispostable.com', 'trashmail.com', 'trashmail.net',
        'getairmail.com', 'mohmal.com', 'maildrop.cc', 'mintemail.com', 'fakeinbox.com',
        'fakemailgenerator.com', 'crazymailing.com', 'generator.email', 'tempinbox.com',
        'mytemp.email', 'inboxbear.com', 'emailondeck.com', 'burnermail.io', 'getnada.com',
        'abcvg.com', 'dropmail.me', 'tempail.com', 'clipmail.eu', 'moakt.com', 'mytempemail.com',
        'nada.ltd', 'inboxkitten.com', 'spam4.me', 'trashmail.de', 'tempmailaddress.com'
    ) THEN
        RAISE EXCEPTION 'Disposable temporary email addresses are not permitted. Please use a valid email.';
    END IF;

    -- 6. Phone Number Validation (7 to 20 valid characters)
    IF NOT (NEW.mobile_number ~ '^[0-9+()\- ]{7,20}$') THEN
        RAISE EXCEPTION 'Contact number must be between 7 and 20 digits.';
    END IF;

    -- 7. Mandatory DPDP Consent
    IF (to_jsonb(NEW) ? 'dpdp_consent') THEN
        IF (to_jsonb(NEW) ->> 'dpdp_consent')::text NOT IN ('true', 't', '1') THEN
            RAISE EXCEPTION 'Privacy consent must be accepted to submit inquiry.';
        END IF;
    END IF;

    -- 8. Timestamps
    NEW.created_at := coalesce(NEW.created_at, now());
    NEW.dpdp_consent_timestamp := coalesce(NEW.dpdp_consent_timestamp, now());

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_inquiry ON public.inquiries;
CREATE TRIGGER trg_validate_inquiry
BEFORE INSERT OR UPDATE ON public.inquiries
FOR EACH ROW
EXECUTE FUNCTION public.fn_validate_inquiry();

