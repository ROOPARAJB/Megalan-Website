-- ==============================================================================
-- 7. Two-Factor Authentication (MFA / Microsoft Authenticator) Verification RPC
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.verify_admin_mfa(p_code TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_clean_code TEXT := regexp_replace(coalesce(p_code, ''), '\s+', '', 'g');
    v_secret TEXT;
    v_backup_codes TEXT;
    v_key_bytes BYTEA;
    v_counter BIGINT;
    v_counter_bytes BYTEA;
    v_hash BYTEA;
    v_offset INT;
    v_truncated BIGINT;
    v_totp INT;
    v_totp_str TEXT;
    v_diff INT;
    v_alphabet TEXT := 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
    v_cleaned TEXT;
    v_val INT;
    v_bits INT;
    v_i INT;
    v_idx INT;
    v_byte INT;
BEGIN
    IF length(v_clean_code) < 6 THEN
        RETURN FALSE;
    END IF;

    -- Fetch 2FA secret from users table
    SELECT two_factor_secret, two_factor_backup_codes
    INTO v_secret, v_backup_codes
    FROM public.users
    WHERE role = 'admin' OR username = 'admin'
    LIMIT 1;

    -- Default fallback secret if user record does not exist
    IF v_secret IS NULL THEN
        v_secret := 'BM6P52QVLSCQU63M5ZQ6SMGXRQV5LCUD';
    END IF;

    -- Check if code matches emergency backup code
    IF v_backup_codes IS NOT NULL AND v_backup_codes ILIKE '%' || v_clean_code || '%' THEN
        RETURN TRUE;
    END IF;

    -- Base32 decode the secret key into bytes
    v_cleaned := upper(rtrim(v_secret, '='));
    v_key_bytes := '\x'::bytea;
    v_val := 0;
    v_bits := 0;

    FOR v_i IN 1..length(v_cleaned) LOOP
        v_idx := position(substr(v_cleaned, v_i, 1) in v_alphabet) - 1;
        IF v_idx >= 0 THEN
            v_val := (v_val << 5) | v_idx;
            v_bits := v_bits + 5;
            IF v_bits >= 8 THEN
                v_byte := (v_val >> (v_bits - 8)) & 255;
                v_key_bytes := v_key_bytes || decode(lpad(to_hex(v_byte), 2, '0'), 'hex');
                v_bits := v_bits - 8;
            END IF;
        END IF;
    END LOOP;

    -- RFC 6238 counter (30-second time interval)
    v_counter := floor(extract(epoch from now()) / 30)::bigint;

    -- Drift tolerance: window of -1, 0, +1 (current ± 30 seconds)
    FOR v_diff IN -1..1 LOOP
        -- Type-safe 8-byte big-endian counter using to_hex and decode
        v_counter_bytes := decode(lpad(to_hex(v_counter + v_diff), 16, '0'), 'hex');

        -- HMAC-SHA1
        v_hash := hmac(v_counter_bytes, v_key_bytes, 'sha1');

        -- Dynamic truncation
        v_offset := get_byte(v_hash, 19) & 15;
        v_truncated := ((get_byte(v_hash, v_offset) & 127) << 24) |
                       ((get_byte(v_hash, v_offset + 1) & 255) << 16) |
                       ((get_byte(v_hash, v_offset + 2) & 255) << 8) |
                       (get_byte(v_hash, v_offset + 3) & 255);

        v_totp := v_truncated % 1000000;
        v_totp_str := lpad(v_totp::text, 6, '0');

        IF v_totp_str = v_clean_code THEN
            RETURN TRUE;
        END IF;
    END LOOP;

    RETURN FALSE;
END;
$$;

